def test_change_scope_and_commit_range(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    assert change_scope.documentation_only(["README.md", "docs/README.md", "LICENSE"])
    assert not change_scope.documentation_only(["README.md", "crates/gh-repoconf/src/lib.rs"])
    assert not change_scope.documentation_only([])
    assert change_scope.changed_paths("", lambda _cmd: (0, ""))[0] is None
    assert change_scope.changed_paths("a..b", lambda _cmd: (0, "README.md\0"))[0] == ["README.md"]
    assert change_scope.changed_paths("a..b", lambda _cmd: (1, "err")) == (
        None,
        "git could not compute diff for `a..b`",
    )
    assert commit_range.resolve_range("pull_request", pr_base="abc123") == "abc123..HEAD"
    assert commit_range.resolve_range("push", push_base="def456") == "def456..HEAD"
    assert commit_range.resolve_range("push", push_base="0" * 40) == ""
    assert commit_range.command("") == ["convco", "check", "-n", "20"]
    assert commit_range.command("a..b") == ["convco", "check", "a..b"]

    out = tmp_path / "out"
    summary = tmp_path / "summary"
    env = {
        "EVENT": "pull_request",
        "PR_BASE": "abc",
        "GITHUB_OUTPUT": str(out),
        "GITHUB_STEP_SUMMARY": str(summary),
    }
    assert change_scope.main([], env=env, git=lambda _cmd: (0, "docs/README.md\0")) == 0
    assert "docs-only=true" in out.read_text(encoding="utf-8")
    assert "Documentation only" in summary.read_text(encoding="utf-8")
    assert (
        change_scope.main([], env=env, git=lambda _cmd: (0, "crates/gh-repoconf/src/lib.rs\0")) == 0
    )
    assert change_scope.main([], env={}, git=lambda _cmd: (0, "")) == 0

    assert commit_range.main(["resolve"], env=env) == 0
    assert commit_range.main(["check"], env=env, run=lambda _cmd: 0) == 0

    def missing(_cmd: object) -> int:
        raise FileNotFoundError

    assert commit_range.main(["check"], env=env, run=missing) == 1

    monkeypatch.setenv("GITHUB_OUTPUT", str(out))
    monkeypatch.setenv("GITHUB_STEP_SUMMARY", str(summary))
    github_actions.set_output("single", "ok")
    github_actions.set_output("multi", "a\nb")
    github_actions.append_summary("line")
    assert "multi<<EOF_multi" in out.read_text(encoding="utf-8")
    assert "line" in summary.read_text(encoding="utf-8")


def test_check_packages_metadata_and_contents(tmp_path: Path) -> None:
    missing = check_packages.contents("gh-repoconf", ["Cargo.toml", "src/lib.rs"])
    assert any(item.kind == "missing-file" for item in missing)

    forbidden = check_packages.contents(
        "gh-repoconf",
        ["Cargo.toml", "README.md", "LICENSE", "src/lib.rs", "features/cli.feature"],
    )
    assert any(item.kind == "forbidden-file" for item in forbidden)

    forbidden_py = check_packages.contents(
        "gh-repoconf",
        ["Cargo.toml", "README.md", "LICENSE", "src/lib.rs", "pyproject.toml"],
    )
    assert any(item.kind == "forbidden-file" for item in forbidden_py)

    forbidden_recipe = check_packages.contents(
        "gh-repoconf",
        ["Cargo.toml", "README.md", "LICENSE", "src/lib.rs", "recipe/recipe.yaml"],
    )
    assert any(item.kind == "forbidden-file" for item in forbidden_recipe)

    assert check_packages.packaging_configs(ROOT) == []
    bad_root = tmp_path / "bad_pkg"
    (bad_root / "crates" / "gh-repoconf").mkdir(parents=True)
    (bad_root / "crates" / "gh-repoconf" / "Cargo.toml").write_text(
        '[package]\nname = "gh-repoconf"\n',
        encoding="utf-8",
    )
    bad_findings = check_packages.packaging_configs(bad_root)
    assert any(item.kind == "invalid-npm-metadata" for item in bad_findings)
    assert any(item.kind == "missing-pypi-manifest" for item in bad_findings)

    (bad_root / "crates" / "gh-repoconf" / "pyproject.toml").write_text(
        '[project]\nname = "wrong"\ndynamic = []\nlicense = "Apache-2.0"\n'
        '[tool.maturin]\nbindings = "pyo3"\nlocked = false\n',
        encoding="utf-8",
    )
    bad_py_findings = check_packages.packaging_configs(bad_root)
    assert sum(1 for item in bad_py_findings if item.kind == "invalid-pypi-manifest") == 5

    assert (
        check_packages.contents("gh-repoconf", ["Cargo.toml", "README.md", "LICENSE", "src/lib.rs"])
        == []
    )
    assert check_packages.metadata(
        "gh-repoconf",
        {"description": {"workspace": True}, "license": {"workspace": True}},
        {"license": "MIT"},
    )
    assert (
        check_packages.metadata(
            "gh-repoconf",
            {
                "description": {"workspace": True},
                "rust-version": {"workspace": True},
                "license": {"workspace": True},
                "homepage": {"workspace": True},
                "repository": {"workspace": True},
                "authors": {"workspace": True},
            },
            {
                "description": "x",
                "rust-version": "1.88",
                "license": "MIT",
                "homepage": "https://example.invalid",
                "repository": "https://example.invalid",
                "authors": ["Archont561"],
            },
        )
        == []
    )

    real_findings = check_packages.check(
        root=ROOT,
        run=lambda _cmd, _root: "\n".join(check_packages.REQUIRED_FILES),
    )
    assert real_findings == []
    assert check_packages.main([]) == 0
    assert check_packages.main(["--list"]) == 0


def test_coverage_normalization_and_threshold(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    core_src = ROOT / "crates" / "gh-repoconf-core" / "src" / "lib.rs"
    cli_src = ROOT / "crates" / "gh-repoconf" / "src" / "lib.rs"
    sample = (
        f"SF:{core_src}\nDA:1,1\nDA:2,1\nLF:0\nLH:0\nend_of_record\n"
        f"SF:{cli_src}\nDA:1,1\nDA:2,0\nDA:3,1\nDA:4,1\nDA:5,1\nDA:6,1\n"
        "DA:7,1\nDA:8,1\nLF:0\nLH:0\nend_of_record\n"
    )
    normalized = check_coverage.normalize_lcov(sample)
    assert "LF:8" in normalized and "LH:7" in normalized
    covered, total = check_coverage.coverage(normalized)
    assert (covered, total) == (9, 10)
    assert check_coverage.meets_target(covered, total)
    assert not check_coverage.meets_target(89, 100)
    assert not check_coverage.meets_target(0, 0)

    lcov_file = tmp_path / "lcov.info"
    lcov_file.write_text(sample, encoding="utf-8")
    monkeypatch.setattr("sys.argv", ["check_coverage.py", str(lcov_file)])
    assert check_coverage.main() == 0

    low_file = tmp_path / "low.info"
    low_file.write_text(
        f"SF:{core_src}\nDA:1,0\nDA:2,0\nend_of_record\n"
        f"SF:{cli_src}\nDA:1,1\nDA:2,0\nend_of_record\n",
        encoding="utf-8",
    )
    monkeypatch.setattr("sys.argv", ["check_coverage.py", str(low_file)])
    assert check_coverage.main() == 1

    with pytest.raises(ValueError, match="Missing source coverage"):
        check_coverage.coverage(f"SF:{core_src}\nDA:1,1\nend_of_record\n")


def test_changelog_render_and_notes(tmp_path: Path) -> None:
    raw = "## v0.1.0 (2026-11-09)\n#### Added\n- Initial CLI\n"
    rendered = changelog.render(changelog.with_unreleased(raw))
    assert "## [Unreleased]" in rendered
    assert "## [0.1.0] - 2026-11-09" in rendered
    assert "### Added" in rendered

    notes = changelog.notes_for(
        lambda _argv: (0, "## Unreleased\n#### Added\n- Feature\n"),
        "0.2.0",
        "2026-11-10",
    )
    assert "## [0.2.0] - 2026-11-10" in notes

    (tmp_path / "CHANGELOG.md").write_text(rendered, encoding="utf-8")
    assert changelog.main(["check"], root=tmp_path, runner=lambda _argv: (0, raw)) == 0
    assert changelog.main(["print"], root=tmp_path, runner=lambda _argv: (0, raw)) == 0
    assert (
        changelog.main(
            ["notes", "0.2.0", "--date", "2026-11-10"],
            root=tmp_path,
            runner=lambda _argv: (0, raw),
        )
        == 0
    )
    assert changelog.main(["regen"], root=tmp_path, runner=lambda _argv: (0, raw)) == 0
    (tmp_path / "CHANGELOG.md").write_text("stale", encoding="utf-8")
    assert changelog.main(["check"], root=tmp_path, runner=lambda _argv: (0, raw)) == 1
    assert changelog.main(["print"], root=tmp_path, runner=lambda _argv: (1, "boom")) == 1


def test_advisory_cache_and_exception(tmp_path: Path) -> None:
    assert advisory_cache.cache_key(datetime.date(2027, 1, 1)) == "2026-W53"
    assert advisory_cache.cache_key(datetime.date(2026, 11, 9)) == "2026-W46"

    cargo_home = tmp_path / ".cargo"
    (cargo_home / "advisory-dbs" / "extra").mkdir(parents=True)
    paths = advisory_cache.default_paths(cargo_home=cargo_home)
    assert len(paths) == 2

    fake_db = tmp_path / "advisory-db"
    (fake_db / ".git").mkdir(parents=True)
    commands: list[list[str]] = []
    assert advisory_cache.clean([fake_db], run=lambda cmd: commands.append(list(cmd))) == [fake_db]
    assert len(commands) == 2

    week_out = tmp_path / "gh_out"
    assert advisory_cache.main(["key"], today=datetime.date(2026, 11, 9), output=week_out) == 0
    assert "week=2026-W46" in week_out.read_text(encoding="utf-8")
    assert advisory_cache.main(["clean", "--cargo-home", str(cargo_home)], run=lambda _c: None) == 0

    assert check_advisory_exception.check(ROOT) == []
    assert check_advisory_exception.main(["--print-path"], root=ROOT) == 0
    assert check_advisory_exception.main([], root=ROOT) == 0
    with pytest.raises(ValueError, match="cannot read"):
        check_advisory_exception.load_lock(tmp_path / "Cargo.lock")
    (tmp_path / "Cargo.lock").write_text(
        '[[package]]\nname = "gh-repoconf"\nversion = "0.1.0"\n',
        encoding="utf-8",
    )
    (tmp_path / ".cargo").mkdir(exist_ok=True)
    (tmp_path / ".cargo" / "audit.toml").write_text(
        '[advisories]\nignore = ["RUSTSEC-2026-0374"]\n',
        encoding="utf-8",
    )
    (tmp_path / "deny.toml").write_text("[advisories]\nignore = []\n", encoding="utf-8")
    assert check_advisory_exception.main([], root=tmp_path) == 1


