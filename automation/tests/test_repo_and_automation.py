def test_sandbox_config_and_lockfile_alignment() -> None:
    assert workspace.ROOT == ROOT
    assert not git_lib.reset_clean_clone(ROOT / "missing-dir")
    assert git_lib.is_shallow_repository(ROOT, lambda _argv, _cwd: (0, "true\n"))
    assert not git_lib.is_shallow_repository(ROOT, lambda _argv, _cwd: (0, "false\n"))

    config = tomllib.loads((ROOT / "pixi-sandbox.toml").read_text(encoding="utf-8"))
    assert config["cargo_vendor"] is True
    bundles = {b["name"]: b for b in config["bundle"]}
    assert bundles["developer"]["environments"] == ["default"]
    assert bundles["developer"]["platforms"] == ["linux-64"]

    restore = (ROOT / "scripts" / "restore.sh").read_text(encoding="utf-8")
    assert "Generated by pixi-sandbox init" in restore
    assert "DEFAULT_BRANCH=sandbox/developer-linux-64" in restore

    lock = (ROOT / "pixi.lock").read_text(encoding="utf-8")
    section = re.search(r"(?ms)^  default:\n(.*?)(?=^  [^ ]+:\n|^packages:\n)", lock)
    assert section is not None
    assert "      linux-64:" in section.group(1)
    locations = re.findall(r"^      - pypi: (.+)$", section.group(1), re.MULTILINE)
    assert locations
    assert all(location.endswith(".whl") for location in locations)


